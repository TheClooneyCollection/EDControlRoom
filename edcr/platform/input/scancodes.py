def resolve_scancode(key: str, *, modifier: bool = False) -> tuple[int, bool]:
    table = MODIFIER_KEYCODES if modifier else KEY_CODES
    try:
        code = table[key.lower()]
    except KeyError:
        raise ValueError(f"Unsupported {'modifier' if modifier else 'key'}: {key}") from None
    extended = code in EXTENDED_KEYS
    return (code & 0x7F if extended else code), extended
